// Ground truth data for BATTU validation.
//
// Every value in GROUND_TRUTH can be independently checked against:
//   - Yahoo Finance       (finance.yahoo.com)
//   - Macrotrends         (macrotrends.net)
//   - SEC EDGAR           (sec.gov)
//   - Koyfin free tier    (koyfin.com)
//
// First-time setup workflow:
//   1. Run `pnpm seed:groundtruth` to populate from Yahoo Finance
//   2. Manually verify high-value fields (EE/ANR/LIQ) against a second source
//   3. Run `pnpm validate` against the live BATTU API
//
// Re-running the seed will OVERWRITE the GROUND_TRUTH block between the
// markers below. Hand-edited values inside the block will be lost. Edits
// outside the markers (types, helpers, tolerance) are preserved.

export type ToleranceBand = 'price' | 'financial' | 'ratio' | 'estimate' | 'liq'

export const TOLERANCE: Record<ToleranceBand, number> = {
  price:     0.01,  // 1%   — prices drift, snapshot timing causes small variance
  financial: 0.005, // 0.5% — should match filings almost exactly
  ratio:     0.03,  // 3%   — methodology differences (TTM vs FY, etc.)
  estimate:  0.05,  // 5%   — consensus aggregation differences across sources
  liq:       0.05,  // 5%   — Claude extraction has minor variance on prose fields
}

export interface GroundTruthField {
  value: number | null    // null = SKIP (field not applicable to this ticker)
  band: ToleranceBand
  source: string          // 'yahoo' | 'yahoo-seed' | 'macrotrends' | 'edgar' | 'koyfin' | 'manual'
  verifiedAt: string      // ISO date string
  notes?: string
}

export interface GroundTruthRecord {
  ticker: string

  // ── DES fields ──
  marketCapB:           GroundTruthField  // billions USD
  sharesOutstandingM:   GroundTruthField  // millions
  peRatioTTM:           GroundTruthField
  epsTTM:               GroundTruthField
  dividendYield:        GroundTruthField  // decimal — 0.005 = 0.5%
  beta:                 GroundTruthField

  // ── FA fields (most recent fiscal year) ──
  revenueB:             GroundTruthField  // billions USD
  grossMargin:          GroundTruthField  // decimal
  operatingMargin:      GroundTruthField
  netMargin:            GroundTruthField
  totalDebtB:           GroundTruthField
  cashAndEquivB:        GroundTruthField

  // ── EE fields (next 12 months consensus) ──
  epsEstimateNTM:       GroundTruthField
  revenueEstimateNTMB:  GroundTruthField

  // ── ANR fields ──
  analystConsensus:     GroundTruthField  // 1=Strong Sell ... 5=Strong Buy
  priceTargetConsensus: GroundTruthField

  // ── HP fields ──
  closePrice1YrAgo:     GroundTruthField  // adjusted close 1yr before HP_REFERENCE_DATE

  // ── LIQ fields (biotechs only — others SKIP) ──
  liqCashRunwayQtrs:    GroundTruthField
  liqTotalLiquidityB:   GroundTruthField
}

