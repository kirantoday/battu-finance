/** Helper for constructing a ground-truth field. */
function gt(
  value: number | null,
  band: ToleranceBand,
  source: string,
  verifiedAt: string,
  notes?: string,
): GroundTruthField {
  return { value, band, source, verifiedAt, ...(notes ? { notes } : {}) }
}

